// These labels are a first pass and need a Japanese speaker's check, or two
// independent sources each, before their results are relied on.

const group =
  (language: string, country: string, kind: CaseKind) =>
  (...rows: (string | [string, ...string[]])[]): FoodCase[] =>
    rows.map((row) => {
      const [name, ...aliasOf] = typeof row === "string" ? [row] : row;
      return { name: name!, language, country, kind, aliasOf };
    });

