export const PANEL_CASES: FoodCase[] = LANGUAGES.flatMap(
  ([language, country], index) => {
    const food = (
      kind: FoodCase["kind"],
      name: string,
      aliasOf: string[] = [],
    ): FoodCase => ({ name, language, country, kind, aliasOf });
    return [
      ...NEW[index]!.map((name) => food("new", name)),
      ...EXISTING.map(([aliasOf, names]) =>
        food("existing", names[index]!, aliasOf),
      ),
      ...OUT_OF_SCOPE[index]!.map((name) => food("out_of_scope", name)),
      ...ABUSE[index]!.map((name) => food("abuse", name)),
    ];
  },
);
